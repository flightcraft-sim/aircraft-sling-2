#!/usr/bin/env python3
"""Losslessly move identical embedded PNGs to one shared set; no Blender required."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

NAMES = ('exterior.glb', 'exterior-lod1.glb', 'exterior-lod2.glb')


def externalize(data, textures):
    size = struct.unpack_from('<I', data, 12)[0]
    doc = json.loads(data[20:20+size])
    binary = data[28+size:]
    removed = set()
    for image in doc.get('images', []):
        if 'uri' in image:
            continue
        view_index = image.pop('bufferView')
        view = doc['bufferViews'][view_index]
        offset = view.get('byteOffset', 0)
        png = binary[offset:offset+view['byteLength']]
        assert png.startswith(b'\x89PNG\r\n\x1a\n')
        digest = hashlib.sha256(png).hexdigest()
        path = 'textures/exterior/shared-' + digest[:16] + '.png'
        assert path not in textures or textures[path] == png
        textures[path] = png
        image['uri'] = path
        image['mimeType'] = 'image/png'
        removed.add(view_index)
    # Repack every remaining binary view; remap all accessor references, including interleaved ones.
    views, remap, blob = [], {}, bytearray()
    for index, view in enumerate(doc['bufferViews']):
        if index in removed:
            continue
        blob.extend(b'\0' * (-len(blob) % 4))
        offset = view.get('byteOffset', 0)
        remap[index] = len(views)
        views.append(dict(view, byteOffset=len(blob)))
        blob.extend(binary[offset:offset+view['byteLength']])
    for accessor in doc['accessors']:
        if 'bufferView' in accessor:
            accessor['bufferView'] = remap[accessor['bufferView']]
        assert 'sparse' not in accessor
    doc['bufferViews'] = views
    blob.extend(b'\0' * (-len(blob) % 4))
    doc['buffers'][0]['byteLength'] = len(blob)
    encoded = json.dumps(doc, separators=(',', ':')).encode()
    encoded += b' ' * (-len(encoded) % 4)
    return (struct.pack('<III', 0x46546c67, 2, 28+len(encoded)+len(blob))
            + struct.pack('<II', len(encoded), 0x4e4f534a) + encoded
            + struct.pack('<II', len(blob), 0x004e4942) + blob)


def prepare(root):
    """Validate/repack all LODs before writing; return bytes and the explicit manifest inventory."""
    textures = {}
    models = {name: externalize((root/name).read_bytes(), textures) for name in NAMES}
    # Idempotent: include already-external images in the inventory too.
    for data in models.values():
        size = struct.unpack_from('<I', data, 12)[0]
        for image in json.loads(data[20:20+size]).get('images', []):
            uri = image['uri']
            assert uri.startswith('textures/exterior/shared-') and uri.endswith('.png') and '..' not in uri
            if uri not in textures:
                textures[uri] = (root/uri).read_bytes()
    return models, textures


def write_embedded_assets(root, paths):
    """Keep the pack's compiled fidelity fixture synchronized after every regeneration."""
    entries = ''.join('    (\n        '+json.dumps(name)+'.to_owned(),\n        include_bytes!("../'+name+'").to_vec(),\n    ),\n' for name in paths)
    (root/'src/exterior_assets.rs').write_text('// Generated by scripts/share-exterior-textures.py.\nstd::collections::BTreeMap::from([\n'+entries+'])\n')


def install(root):
    before = sum((root/name).stat().st_size for name in NAMES)
    models, textures = prepare(root)
    for name, data in textures.items():
        path = root/name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    for name, data in models.items():
        (root/name).write_bytes(data)
    definition = json.loads((root/'exterior.json').read_text())
    definition['textures'] = sorted(textures)
    manifest = json.loads((root/'pack.json').read_text())
    for index, entry in enumerate(manifest['exterior']):
        if entry['aircraft'] == definition['aircraft']:
            manifest['exterior'][index] = definition
    (root/'exterior.json').write_text(json.dumps(definition, indent=2)+'\n')
    (root/'pack.json').write_text(json.dumps(manifest, indent=2)+'\n')
    write_embedded_assets(root, [*models, *sorted(textures)])
    return dict(before_glb_bytes=before, models={name: len(data) for name, data in models.items()},
                textures={name: len(data) for name, data in textures.items()},
                after_download_bytes=sum(map(len, models.values()))+sum(map(len, textures.values())))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('pack', type=Path)
    parser.add_argument('--receipt', type=Path)
    args = parser.parse_args()
    receipt = install(args.pack)
    if args.receipt:
        args.receipt.write_text(json.dumps(receipt, indent=2)+'\n')
    print(json.dumps(receipt, indent=2))
